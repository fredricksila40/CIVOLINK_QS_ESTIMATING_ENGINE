"""Master release orchestrator (release tooling).

Pipeline (strict order, fail-closed):
  1. PyInstaller --onedir build  -> dist/CIVOLINK-QS/CIVOLINK-QS.exe
  2. Sign the inner executable (skipped only with --allow-unsigned).
  3. Verify its signature + trust chain (skipped likewise).
  4. Compile the Inno Setup installer -> release/CIVOLINK-QS-Setup-<v>.exe
     (skipped with a warning when Inno Setup is absent in dev mode).
  5. Sign the installer.
  6. Verify the installer.
  7. Regenerate dist/RELEASE_MANIFEST.json: canonical version from
     qs_engine.__version__ plus fresh SHA-256 hashes of the built
     artefacts (fail-closed for signed releases).

Any required step that fails aborts with exit code 1 and never marks
the build successful. Development use: ``python scripts/build_release.py
--allow-unsigned``.
"""

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ENGINE_ROOT))

APP_NAME = "CIVOLINK-QS"
SPEC_REFERENCE = "civolink.spec (one-file dev builds; kept untouched)"

# Build settings mirrored from civolink.spec (the reference for hidden
# imports, bundled data, and the High-DPI manifest). The spec file
# itself stays one-file; the release pipeline needs onedir layout for
# the Inno Setup installer, so the equivalent settings travel here.
HIDDEN_IMPORTS = [
    "fastapi", "starlette", "pydantic", "anyio", "uvicorn",
    "uvicorn.logging", "uvicorn.loops.auto",
    "uvicorn.protocols.http.auto", "uvicorn.protocols.websockets.auto",
    "uvicorn.lifespan.on", "multipart", "httpx",
    "reportlab", "reportlab.lib", "reportlab.pdfbase",
    "reportlab.pdfgen", "reportlab.platypus",
    "sqlite3", "docx", "lxml",
]
BUNDLED_DATA = [
    (os.path.join("qs_engine", "master_data", "tables", "*.json"),
     os.path.join("qs_engine", "master_data", "tables")),
    (os.path.join("config", "company_profile.json"), "config"),
    (os.path.join("scripts", "*.py"), "scripts"),
]
APP_MANIFEST = "civolink.manifest"
ISS_SCRIPT = "civolink_setup.iss"


class BuildError(Exception):
    """Release step failed: abort, never mark success."""


def app_version():
    """Distribution version (single source: qs_engine.__version__)."""
    from qs_engine import __version__
    return str(__version__)


def inner_exe_path(engine_root=None):
    """dist/CIVOLINK-QS/CIVOLINK-QS.exe for the onedir layout."""
    root = Path(engine_root) if engine_root else ENGINE_ROOT
    name = "CIVOLINK-QS.exe"
    return str(root / "dist" / "CIVOLINK-QS" / name)


def installer_path(version, engine_root=None):
    """release/CIVOLINK-QS-Setup-<version>.exe."""
    root = Path(engine_root) if engine_root else ENGINE_ROOT
    return str(root / "release" / f"CIVOLINK-QS-Setup-{version}.exe")


def sha256_file(path):
    """SHA-256 hex digest of a file; None when it does not exist.

    Absent artefacts are recorded as null rather than guessed: a
    development tree may legitimately lack the installer or archive,
    and a fabricated digest would be dishonest provenance.
    """
    try:
        digest = hashlib.sha256()
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
        return digest.hexdigest()
    except OSError:
        return None


def manifest_path(engine_root=None):
    """dist/RELEASE_MANIFEST.json (regenerated by every release build)."""
    root = Path(engine_root) if engine_root else ENGINE_ROOT
    return str(root / "dist" / "RELEASE_MANIFEST.json")


def release_manifest(version=None, engine_root=None, test_baseline=None):
    """Assemble the release manifest with fresh hashes.

    Versioning comes from ``qs_engine.__version__`` via
    ``app_version()`` — the single canonical source; nothing in this
    manifest may name a version the package does not carry. File hashes
    are computed from the artefacts on disk (null when absent).
    ``test_baseline`` is provenance supplied by the caller/CI and is
    otherwise carried forward from the previous manifest, never
    invented. Test fixtures (``tests/fixtures/assemblies``) are
    deliberately absent: they are not shipped content.
    """
    root = Path(engine_root) if engine_root else ENGINE_ROOT
    resolved = str(version) if version else app_version()
    manifest_file = Path(manifest_path(root))
    previous = {}
    if manifest_file.is_file():
        try:
            previous = json.loads(manifest_file.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            previous = {}
    if test_baseline is None and isinstance(previous, dict):
        test_baseline = previous.get("test_baseline")
    manifest = {
        "version": resolved,
        "build_timestamp": datetime.now(timezone.utc).strftime(
            "%Y-%m-%dT%H:%M:%SZ"),
        "exe_sha256": sha256_file(inner_exe_path(root)),
        "zip_sha256": sha256_file(
            root / "dist" / f"CIVOLINK-QS-v{resolved}.zip"),
        "installer_sha256": sha256_file(
            installer_path(resolved, root)),
    }
    if test_baseline is not None:
        manifest["test_baseline"] = str(test_baseline)
    return manifest


def write_release_manifest(version=None, engine_root=None,
                           test_baseline=None, required=False):
    """Regenerate the manifest atomically; returns the written path.

    ``required=True`` (signed release mode) fails closed when the
    executable digest is missing — a release checksum manifest without
    the executable hash is not a release. Development builds tolerate
    partially built trees and record null hashes instead.
    """
    root = Path(engine_root) if engine_root else ENGINE_ROOT
    manifest = release_manifest(version=version, engine_root=root,
                                test_baseline=test_baseline)
    if required and not manifest.get("exe_sha256"):
        raise BuildError(
            "release manifest requires the executable SHA-256 but "
            f"{inner_exe_path(root)} is missing or unreadable")
    target = Path(manifest_path(root))
    tmp = target.with_name(target.name + ".tmp")
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp.write_text(json.dumps(manifest, indent=2) + "\n",
                       encoding="utf-8")
        os.replace(tmp, target)
    except OSError as exc:
        try:
            tmp.unlink()
        except OSError:
            pass
        raise BuildError(f"Could not write release manifest {target}: "
                         f"{exc}") from exc
    return target


def _data_separator():
    return ";" if sys.platform.startswith("win") else ":"


def pyinstaller_args():
    """CLI args replicating civolink.spec for an onedir release build."""
    sep = _data_separator()
    args = ["--noconfirm", "--clean", "--onedir", "--windowed",
            "--name", APP_NAME, "--manifest", APP_MANIFEST]
    for name in HIDDEN_IMPORTS:
        args += ["--hidden-import", name]
    for source, dest in BUNDLED_DATA:
        args += ["--add-data", f"{source}{sep}{dest}"]
    args.append(os.path.join("qs_engine", "__main__.py"))
    return args


def _sign_module():
    """sign_artifacts module, imported lazily on first use.

    Indirection (instead of a top-level import) keeps this module
    importable without touching the ``scripts`` package, so test
    suites that need a pristine ``sys.modules["scripts"]`` (e.g. the
    frozen-engine regression tests resolving an external checkout)
    are never disturbed by importing the release tooling.
    """
    from scripts import sign_artifacts
    return sign_artifacts


def _run_pyinstaller(args):
    """Execute the PyInstaller build (seam for tests to stub)."""
    try:
        from PyInstaller.__main__ import run as pyinstaller_run
    except ImportError as exc:
        raise BuildError(
            "PyInstaller is not installed in this environment "
            "(pip install pyinstaller).") from exc
    pyinstaller_run(args)


def build_onedir():
    """Run the onedir bundle; fail closed when the exe is missing."""
    print("build: PyInstaller --onedir CIVOLINK-QS ...")
    _run_pyinstaller(pyinstaller_args())
    target = inner_exe_path()
    if not os.path.isfile(target):
        raise BuildError(
            f"PyInstaller finished without producing {target}")
    print(f"build: produced {target}")
    return target


def _run_command(args):
    """Run an external tool, capturing output (seam for tests)."""
    import subprocess
    return subprocess.run(args, capture_output=True, text=True,
                          timeout=600)


def compile_installer(version, _sign=None):
    """Compile civolink_setup.iss with Inno Setup; fail closed."""
    sign = _sign if _sign is not None else _sign_module()
    iscc = sign.find_iscc()
    if iscc is None:
        raise sign.ToolNotFoundError(
            "Inno Setup compiler (iscc) not found: install Inno "
            "Setup 6 or add it to PATH.")
    script = str(ENGINE_ROOT / ISS_SCRIPT)
    if not os.path.isfile(script):
        raise BuildError(f"Installer script missing: {script}")
    print(f"installer: compiling {ISS_SCRIPT} ...")
    completed = _run_command(
        [iscc, f"/DMyAppVersion={version}", script])
    target = installer_path(version)
    if completed.returncode != 0 or not os.path.isfile(target):
        raise BuildError(
            "Inno Setup compilation failed "
            f"(exit {completed.returncode}): "
            f"{(completed.stdout + completed.stderr).strip()[-2000:]}")
    print(f"installer: produced {target}")
    return target


def parse_args(argv=None):
    """Release flags (pure; headless-testable)."""
    parser = argparse.ArgumentParser(
        prog="build_release",
        description="CIVOLINK QS fail-closed release pipeline")
    parser.add_argument("--allow-unsigned", action="store_true",
                        help="development mode: skip signing and "
                             "verification (never for releases)")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    """Orchestrate the release; returns a process exit code."""
    sign = _sign_module()
    args = parse_args(argv)
    version = app_version()
    config = sign.SigningConfig.from_env()
    if args.allow_unsigned:
        config.allow_unsigned = True
    if not config.allow_unsigned and not config.credentials_ok():
        print("RELEASE FAILED: signing is required but no credentials "
              "are configured (set CIVOLINK_SIGN_CERT_PATH or "
              "CIVOLINK_SIGN_THUMBPRINT, or pass --allow-unsigned for "
              "local dev builds only).")
        return 1
    signing = not config.allow_unsigned

    try:
        inner = build_onedir()
        if signing:
            signtool = sign.find_signtool()
            if signtool is None:
                raise sign.ToolNotFoundError(
                    "signtool.exe not found: install the Windows SDK "
                    "or add it to PATH.")
            sign.sign_file(signtool, inner, config)
            sign.verify_file(signtool, inner)
            print(f"signed + verified: {inner}")
        else:
            print("signing skipped (--allow-unsigned development mode)")

        installer = None
        try:
            installer = compile_installer(version)
        except sign.ToolNotFoundError as exc:
            if config.allow_unsigned:
                print(f"warning: {exc} Skipping installer step.")
            else:
                raise
        if installer is not None and signing:
            signtool = sign.find_signtool()
            if signtool is None:
                raise sign.ToolNotFoundError(
                    "signtool.exe not found for installer signing.")
            sign.sign_file(signtool, installer, config)
            sign.verify_file(signtool, installer)
            print(f"signed + verified: {installer}")
        elif installer is not None:
            print("installer left unsigned (--allow-unsigned "
                  "development mode)")
    except (BuildError, sign.SigningError,
            sign.VerificationError,
            sign.ToolNotFoundError) as exc:
        print(f"RELEASE FAILED: {exc}")
        return 1
    try:
        # Regenerate the checksum manifest from the canonical package
        # version with hashes of the artefacts this build produced.
        write_release_manifest(version=version, required=signing)
    except BuildError as exc:
        print(f"RELEASE FAILED: {exc}")
        return 1
    print("RELEASE OK")
    if installer is not None:
        print(f"  installer: {installer}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
